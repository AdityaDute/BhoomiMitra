export function getPracticesBySystem(system: 'organic' | 'zbnf' | 'both'): FarmingPractice[] {
  if (system === 'both') return farmingPractices;
  return farmingPractices.filter(p => p.system === system || p.system === 'both');
}

export function getPracticesByCategory(category: string): FarmingPractice[] {
  return farmingPractices.filter(p => p.category === category);
}

export function searchPractices(query: string): FarmingPractice[] {
  const lower = query.toLowerCase();
  return farmingPractices.filter(p =>
    p.name.toLowerCase().includes(lower) ||
    p.purpose.toLowerCase().includes(lower) ||
    p.description.toLowerCase().includes(lower) ||
    p.category.toLowerCase().includes(lower)
  );
}
